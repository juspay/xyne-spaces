import { allThemes } from './tokens/palettes';
import { SEMANTIC_ROLES, cssVar } from './tokens/roles';

/**
 * Emits the Spaces roles as one Uniwind theme block per variant.
 *
 * Written to its own file and imported by `global.css`, so not one line of the
 * classic design's CSS changes: Uniwind accumulates `@variant` blocks across
 * imported files rather than replacing them, so these declarations join the
 * existing `light` and `dark` themes instead of shadowing them.
 */
export function generateCss(): string {
  const blocks = allThemes().map(theme => {
    const declarations = SEMANTIC_ROLES.map(role => `      ${cssVar(role)}: ${theme.roles[role]};`);

    return [`    @variant ${theme.variant} {`, ...declarations, '    }'].join('\n');
  });

  return [
    '/*',
    ' * Generated by `npm run theme:generate` — do not edit.',
    ' * Source of truth: src/design-system/tokens/',
    ' */',
    '',
    '@layer theme {',
    '  :root {',
    ...blocks,
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Relative to the app root, so the script and the freshness test agree. */
export const GENERATED_CSS_PATH = 'src/design-system/generated/spaces-tokens.css';

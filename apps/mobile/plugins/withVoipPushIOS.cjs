/**
 * Native owner of every CallKit report. Generated into AppDelegate.swift so an
 * incoming call rings — and stops ringing — with the JS runtime suspended or
 * dead: INCOMING_CALL rings with a 30s timeout, CALL_DISMISS / MISSED_CALL end
 * the ring with the typed reason, and a stale ring (backend `sentAt` older than
 * 30s — held by APNs while offline) is logged as missed without ringing.
 *
 * The CallKit UUID is derived from the backend callId exactly like
 * src/services/CallKitUUID.ts, so JS can end a natively-reported ring from a
 * bare callId. Keep the two in sync.
 */
const CALL_PUSH_ROUTER_SWIFT = `
// MARK: - Lotus call push router (generated by with-voip-push-ios)
//
// Single native owner of CallKit reports, so an incoming call rings — and stops
// ringing — without the JS runtime:
//   • INCOMING_CALL              → reportNewIncomingCall + ring timeout
//   • CALL_DISMISS / MISSED_CALL → end the ringing call with the typed reason,
//     matched by any identifier the ring carried; a dismiss that beats its
//     ring keeps that ring from ringing
//   • visible CALL_DISMISS / MISSED_CALL pushes never reach this process in the
//     background — the Notification Service Extension relays them through the
//     App Group and a Darwin notification (see relayCallControlPush there)
//   • stale ring (sentAt older than the threshold) → report + end immediately,
//     so a push APNs held while the device was offline never rings hours later
//   • the server is told "ringing" when CallKit shows the call and "declined" when
//     the user ends it while it rings (LotusCallApi below) — neither waits on JS
//
// CallKit UUIDs are derived from the backend callId exactly like
// src/services/CallKitUUID.ts (deriveCallKitUUID), so JS and native agree on
// the identifier without sharing any state.
final class LotusCallPushRouter: NSObject, CXCallObserverDelegate {
  static let shared = LotusCallPushRouter()

  /// Keep in sync with CALL_RING_TIMEOUT_MS (src/services/PushNotificationPayload.ts).
  static let ringTimeoutSeconds: TimeInterval = 30
  /// Keep in sync with STALE_CALL_PUSH_THRESHOLD_MS.
  static let stalePushThresholdSeconds: TimeInterval = 30
  private static let minPlausibleSentAt: TimeInterval = 1_577_836_800 // 2020-01-01

  /// CXCallEndedReason raw values as consumed by RNCallKeep.endCall(withUUID:reason:).
  enum EndReason: Int32 {
    case failed = 1
    case remoteEnded = 2
    case unanswered = 3
    case answeredElsewhere = 4
    case declinedElsewhere = 5
  }

  struct CallPushInfo {
    let type: String
    let callId: String
    /// Every identifier the push carries for its call, most specific first.
    /// A ring and its dismiss can name the call by different fields.
    let callIds: [String]
    let callUUID: String
    let callerName: String
    let handle: String
    let hasVideo: Bool
    let sentAt: Date?
    let reason: String
  }

  /// How long a ring is remembered by every identifier it carried.
  static let ringMemorySeconds: TimeInterval = 120
  /// How long a dismiss that found nothing ringing suppresses a late ring push.
  /// Short on purpose: a user re-invited to a call they declined must ring again.
  static let dismissMemorySeconds: TimeInterval = 15
  /// App Group key the Notification Service Extension relays call-control pushes under.
  static let relayedDismissalsKey = "lotus.pendingCallDismissals"
  /// A relayed dismiss older than the dismiss window can no longer be racing a ring.
  static let relayedDismissalMaxAgeSeconds: TimeInterval = dismissMemorySeconds

  private let callObserver = CXCallObserver()
  private var ringTimers: [String: DispatchWorkItem] = [:]
  /// Call identifier -> the UUID CallKit rang that call under.
  private var ringUUIDsByCallId: [String: (uuid: String, at: Date)] = [:]
  /// Call identifier or UUID -> a dismiss that arrived with nothing ringing.
  private var dismissedCalls: [String: (at: Date, sentAt: Date?, reason: EndReason)] = [:]

  /// What the server is told about a ring, by the CallKit UUID it rings under.
  private struct Ring {
    let callId: String
    /// You were already on a call (SIM, another VoIP app, ours) when this one arrived.
    let onAnotherCall: Bool
    let at: Date
    var statusReported: Bool
  }
  private var rings: [String: Ring] = [:]

  private override init() {
    super.init()
    callObserver.setDelegate(self, queue: DispatchQueue.main)
    // Posted by the react-native-callkeep patch when CallKit performs a CXEndCallAction.
    NotificationCenter.default.addObserver(
      self,
      selector: #selector(handleEndCallAction(_:)),
      name: Notification.Name("RNCallKeepPerformEndCallActionNotification"),
      object: nil
    )
    observeRelayedDismissals()
    drainRelayedDismissals()
  }

  /// Touching 'shared' at launch registers the relay observer and drains pushes the
  /// extension recorded while no app process existed, before any ring can arrive.
  func start() {}

  // MARK: Payload parsing

  private static func string(_ value: Any?) -> String? {
    if let text = value as? String {
      let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
      return trimmed.isEmpty ? nil : trimmed
    }
    if let number = value as? NSNumber {
      return number.stringValue
    }
    return nil
  }

  private static func dictionary(_ value: Any?) -> [String: Any] {
    if let dict = value as? [String: Any] {
      return dict
    }
    if let raw = value as? String,
       let data = raw.data(using: .utf8),
       let parsed = try? JSONSerialization.jsonObject(with: data) as? [String: Any] {
      return parsed
    }
    return [:]
  }

  /// Every shape the backend has used, most specific first: metadata.callId,
  /// callId, relatedEntityId, a nested data dict, actionUrl (…/call/<id>), uuid.
  private static func callIdCandidates(in payload: [AnyHashable: Any], metadata: [String: Any]) -> [String] {
    let nested = dictionary(payload["data"])
    var candidates = [
      string(metadata["callId"]),
      string(payload["callId"]),
      string(payload["relatedEntityId"]),
      string(nested["callId"]),
      string(dictionary(nested["metadata"])["callId"])
    ]
    if let actionUrl = string(payload["actionUrl"]) ?? string(metadata["actionUrl"]),
       let url = URL(string: actionUrl) {
      let parts = url.pathComponents
      if let index = parts.firstIndex(of: "call"), index + 1 < parts.count {
        candidates.append(parts[index + 1])
      }
    }
    candidates.append(string(payload["uuid"]))
    var seen = Set<String>()
    return candidates.compactMap { $0 }.filter { seen.insert($0).inserted }
  }

  /// Mirrors deriveCallKitUUID(): canonical UUIDs pass through lower-cased,
  /// anything else becomes a v5-shaped UUID from SHA-256(callId).
  static func callKitUUID(for callId: String) -> String {
    let trimmed = callId.trimmingCharacters(in: .whitespacesAndNewlines)
    if UUID(uuidString: trimmed) != nil {
      return trimmed.lowercased()
    }
    var bytes = Array(SHA256.hash(data: Data(trimmed.utf8))).prefix(16).map { UInt8($0) }
    bytes[6] = (bytes[6] & 0x0f) | 0x50
    bytes[8] = (bytes[8] & 0x3f) | 0x80
    let hex = Array(bytes.map { String(format: "%02x", $0) }.joined())
    let groups = [hex[0..<8], hex[8..<12], hex[12..<16], hex[16..<20], hex[20..<32]]
    return groups.map { String($0) }.joined(separator: "-")
  }

  private static func normalizeEpochSeconds(_ value: Double) -> Double {
    // Anything below 1e11 cannot be a millisecond timestamp after 1973 — treat as seconds.
    return value < 1e11 ? value : value / 1000
  }

  private static func epochDate(_ value: Any?) -> Date? {
    var seconds: Double?
    if let number = value as? NSNumber {
      seconds = normalizeEpochSeconds(number.doubleValue)
    } else if let text = string(value) {
      if let numeric = Double(text) {
        seconds = normalizeEpochSeconds(numeric)
      } else {
        let fractional = ISO8601DateFormatter()
        fractional.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        if let date = fractional.date(from: text) ?? ISO8601DateFormatter().date(from: text),
           date.timeIntervalSince1970 >= minPlausibleSentAt {
          return date
        }
        return nil
      }
    }
    guard let resolved = seconds, resolved >= minPlausibleSentAt else {
      return nil
    }
    return Date(timeIntervalSince1970: resolved)
  }

  /// Deliberately not createdAt / startedAt: those describe the call, and a user
  /// invited ten minutes into a running call must still ring.
  private static func sentAt(in payload: [AnyHashable: Any], metadata: [String: Any]) -> Date? {
    for key in ["sentAt", "sent_at", "pushSentAt"] {
      if let date = epochDate(payload[key]) ?? epochDate(metadata[key]) {
        return date
      }
    }
    return nil
  }

  /// - Parameter defaultType: VoIP pushes are calls by construction; APNs pushes are not.
  static func parse(_ payload: [AnyHashable: Any], defaultType: String?) -> CallPushInfo? {
    let metadata = dictionary(payload["metadata"])
    let callIds = callIdCandidates(in: payload, metadata: metadata)
    guard let callId = callIds.first else {
      return nil
    }
    guard let type = (string(payload["type"]) ?? string(metadata["type"]) ?? defaultType)?.uppercased() else {
      return nil
    }
    let callerName = string(metadata["callerName"])
      ?? string(payload["callerName"])
      ?? string(payload["msg_title"])
      ?? "Lotus Caller"
    let handle = string(payload["handle"]) ?? string(metadata["callerId"]) ?? "lotus-call"
    let callType = (string(metadata["callType"]) ?? string(payload["callType"]) ?? "").uppercased()
    let reason = (string(metadata["reason"]) ?? string(payload["reason"]) ?? "").lowercased()
    return CallPushInfo(
      type: type,
      callId: callId,
      callIds: callIds,
      callUUID: callKitUUID(for: callId),
      callerName: callerName,
      handle: handle,
      hasVideo: callType == "VIDEO",
      sentAt: sentAt(in: payload, metadata: metadata),
      reason: reason
    )
  }

  static func isDismissType(_ type: String) -> Bool {
    return type == "CALL_DISMISS" || type == "MISSED_CALL"
  }

  /// Mirrors resolveCallEndReason() in src/services/PushNotificationPayload.ts.
  static func endReason(for info: CallPushInfo) -> EndReason {
    if info.type == "MISSED_CALL" {
      return .unanswered
    }
    switch info.reason {
    case "answered", "accepted", "joined", "answered_elsewhere", "answered-elsewhere", "answeredelsewhere":
      return .answeredElsewhere
    case "declined", "rejected", "busy", "declined_elsewhere", "declined-elsewhere", "declinedelsewhere":
      return .declinedElsewhere
    case "timeout", "timed_out", "ring_timeout", "unanswered", "missed", "no_answer", "no-answer", "noanswer", "unavailable", "expired":
      return .unanswered
    case "cancelled", "canceled", "caller_cancelled", "caller_canceled", "ended", "call_ended", "hangup", "hung_up", "remote_ended", "left":
      return .remoteEnded
    case "failed", "error":
      return .failed
    default:
      return .answeredElsewhere
    }
  }

  // MARK: System call state — CXCallObserver is the source of truth, not our own maps

  private func systemCall(for uuidString: String) -> CXCall? {
    guard let uuid = UUID(uuidString: uuidString) else {
      return nil
    }
    return callObserver.calls.first { $0.uuid == uuid && !$0.hasEnded }
  }

  /// Already in a call (connected or being dialled) — a SIM call, another VoIP app, or ours.
  /// Checked before the new ring is reported, so it is never counted. A call that is only
  /// ringing alongside doesn't make you busy. CXCallObserver needs no extra permission.
  private func isOnAnotherCall() -> Bool {
    return callObserver.calls.contains { !$0.hasEnded && ($0.hasConnected || $0.isOutgoing) }
  }

  private func isRinging(_ uuidString: String) -> Bool {
    guard let call = systemCall(for: uuidString) else {
      return false
    }
    return !call.hasConnected && !call.isOutgoing
  }

  /// The call CallKit is ringing (or has connected) for this push, matched by
  /// every identifier the push carries rather than only the UUID derived from
  /// its first one.
  private func systemCall(matching info: CallPushInfo) -> CXCall? {
    pruneCallMemory()
    var uuids = [info.callUUID]
    for id in info.callIds {
      if let known = ringUUIDsByCallId[id] {
        uuids.append(known.uuid)
      }
      uuids.append(LotusCallPushRouter.callKitUUID(for: id))
    }
    for uuid in uuids {
      if let call = systemCall(for: uuid) {
        return call
      }
    }
    return nil
  }

  private func rememberRing(_ info: CallPushInfo, uuid: String, onAnotherCall: Bool) {
    pruneCallMemory()
    let now = Date()
    for id in info.callIds {
      ringUUIDsByCallId[id] = (uuid: uuid, at: now)
    }
    rings[uuid.lowercased()] = Ring(
      callId: info.callId,
      onAnotherCall: onAnotherCall,
      at: now,
      statusReported: false
    )
  }

  private func rememberDismissal(_ info: CallPushInfo, reason: EndReason) {
    pruneCallMemory()
    let now = Date()
    for key in info.callIds + [info.callUUID] {
      dismissedCalls[key] = (at: now, sentAt: info.sentAt, reason: reason)
    }
  }

  /// The UUID a ring for this call was reported under, while CXCallObserver may not
  /// list it yet: reportNewIncomingCall is asynchronous, and a dismiss can land inside
  /// that window.
  private func rememberedRingUUID(for info: CallPushInfo) -> String? {
    pruneCallMemory()
    for id in info.callIds {
      if let known = ringUUIDsByCallId[id] {
        return known.uuid
      }
    }
    return nil
  }

  /// The reason a ring push is already obsolete: its call was dismissed before
  /// the ring arrived. A ring the backend sent after that dismiss is a fresh
  /// invite and rings — judged on backend timestamps only, so clock skew between
  /// the device and the server cannot resurrect a cancelled ring.
  private func dismissalPreceding(_ info: CallPushInfo) -> EndReason? {
    pruneCallMemory()
    for key in info.callIds + [info.callUUID] {
      guard let dismissal = dismissedCalls[key] else {
        continue
      }
      if let ringSentAt = info.sentAt, let dismissSentAt = dismissal.sentAt, ringSentAt > dismissSentAt {
        continue
      }
      return dismissal.reason
    }
    return nil
  }

  // MARK: Relay from the Notification Service Extension

  private static var appGroupIdentifier: String? {
    Bundle.main.object(forInfoDictionaryKey: "AppGroupIdentifier") as? String
  }

  private func observeRelayedDismissals() {
    guard let group = LotusCallPushRouter.appGroupIdentifier else {
      return
    }
    CFNotificationCenterAddObserver(
      CFNotificationCenterGetDarwinNotifyCenter(),
      Unmanaged.passUnretained(self).toOpaque(),
      { _, _, _, _, _ in
        LotusCallPushRouter.shared.drainRelayedDismissals()
      },
      "\\(group).call-dismiss" as CFString,
      nil,
      .deliverImmediately
    )
  }

  /// Ends rings for the call-control pushes the extension recorded. Entries are
  /// consumed once; a stale one (the app was dead for a minute) is dropped so it
  /// cannot suppress a later ring for the same call.
  func drainRelayedDismissals() {
    guard let group = LotusCallPushRouter.appGroupIdentifier,
          let defaults = UserDefaults(suiteName: group),
          let entries = defaults.array(forKey: LotusCallPushRouter.relayedDismissalsKey) as? [[String: Any]],
          !entries.isEmpty else {
      return
    }
    defaults.removeObject(forKey: LotusCallPushRouter.relayedDismissalsKey)
    let now = Date().timeIntervalSince1970
    for entry in entries {
      guard let receivedAt = entry["receivedAt"] as? Double,
            now - receivedAt < LotusCallPushRouter.relayedDismissalMaxAgeSeconds,
            let payload = entry["payload"] as? [String: Any] else {
        continue
      }
      NSLog("[LotusCallPush] relayed %@ from the notification extension", (payload["type"] as? String) ?? "call push")
      _ = handleRemoteDismissIfNeeded(payload)
    }
  }

  private func pruneCallMemory() {
    let now = Date()
    ringUUIDsByCallId = ringUUIDsByCallId.filter {
      now.timeIntervalSince($0.value.at) < LotusCallPushRouter.ringMemorySeconds
    }
    rings = rings.filter {
      now.timeIntervalSince($0.value.at) < LotusCallPushRouter.ringMemorySeconds
    }
    dismissedCalls = dismissedCalls.filter {
      now.timeIntervalSince($0.value.at) < LotusCallPushRouter.dismissMemorySeconds
    }
  }

  func callObserver(_ callObserver: CXCallObserver, callChanged call: CXCall) {
    if call.hasConnected || call.hasEnded {
      cancelRingTimeout(call.uuid.uuidString)
    } else {
      reportRingStatusIfRinging(call.uuid.uuidString)
    }
  }

  // MARK: Telling the server — ringing, declined

  /// Tells the server this device is ringing (or busy), once per ring and only when CallKit
  /// really shows the call: a ring it filtered (Do Not Disturb, a blocked caller) never does.
  private func reportRingStatusIfRinging(_ uuidString: String) {
    let uuid = uuidString.lowercased()
    guard var ring = rings[uuid], !ring.statusReported, isRinging(uuid) else {
      return
    }
    ring.statusReported = true
    rings[uuid] = ring
    LotusCallApi.reportRingStatus(callId: ring.callId, busy: ring.onAnotherCall)
  }

  /// The user ended a call from the CallKit UI. The notification arrives before the action is
  /// fulfilled, so the call is still listed: one that is still ringing is being declined. The
  /// server is told from here because iOS suspends the app moments later — too soon to count
  /// on JS, which may not even have started — and it only accepts a decline while the call rings.
  @objc private func handleEndCallAction(_ notification: Notification) {
    guard let uuid = (notification.userInfo?["callUUID"] as? String)?.lowercased(),
          isRinging(uuid),
          let ring = rings[uuid] else {
      return
    }
    NSLog("[LotusCallPush] %@ declined from CallKit — declining on the server", ring.callId)
    LotusCallApi.decline(callId: ring.callId)
  }

  // MARK: Ring timeout — native, so it fires while JS is suspended

  private func scheduleRingTimeout(_ uuidString: String) {
    let key = uuidString.lowercased()
    cancelRingTimeout(key)
    let work = DispatchWorkItem { [weak self] in
      guard let self = self else {
        return
      }
      self.ringTimers.removeValue(forKey: key)
      guard self.isRinging(key) else {
        return
      }
      NSLog("[LotusCallPush] ring timeout — ending %@ as unanswered", key)
      RNCallKeep.endCall(withUUID: key, reason: EndReason.unanswered.rawValue)
    }
    ringTimers[key] = work
    DispatchQueue.main.asyncAfter(deadline: .now() + LotusCallPushRouter.ringTimeoutSeconds, execute: work)
  }

  private func cancelRingTimeout(_ uuidString: String) {
    let key = uuidString.lowercased()
    ringTimers[key]?.cancel()
    ringTimers.removeValue(forKey: key)
  }

  // MARK: Reporting

  private func report(
    _ info: CallPushInfo,
    uuid: String? = nil,
    payload: [AnyHashable: Any],
    fromPushKit: Bool,
    completion: @escaping () -> Void
  ) {
    RNCallKeep.reportNewIncomingCall(
      uuid ?? info.callUUID,
      handle: info.handle,
      handleType: "generic",
      hasVideo: info.hasVideo,
      localizedCallerName: info.callerName,
      supportsHolding: false,
      supportsDTMF: false,
      supportsGrouping: false,
      supportsUngrouping: false,
      fromPushKit: fromPushKit,
      payload: payload,
      withCompletionHandler: completion
    )
  }

  /// Rings a new call and, once CallKit shows it, tells the server this device is ringing.
  private func ring(
    _ info: CallPushInfo,
    payload: [AnyHashable: Any],
    fromPushKit: Bool,
    completion: @escaping () -> Void
  ) {
    let uuid = info.callUUID
    let onAnotherCall = isOnAnotherCall()
    // JS reads this flag for its own (fallback) ring-status report.
    var marked = payload
    marked["lotusOnAnotherCall"] = onAnotherCall
    rememberRing(info, uuid: uuid, onAnotherCall: onAnotherCall)
    report(info, payload: marked, fromPushKit: fromPushKit) { [weak self] in
      DispatchQueue.main.async {
        self?.reportRingStatusIfRinging(uuid)
      }
      completion()
    }
    scheduleRingTimeout(uuid)
  }

  /// PushKit requires reportNewIncomingCall for every VoIP push. Report, then end
  /// at once: nothing rings, and the system call log gets the right entry.
  private func reportAndEnd(
    _ info: CallPushInfo,
    payload: [AnyHashable: Any],
    reason: EndReason,
    completion: @escaping () -> Void
  ) {
    let uuid = info.callUUID
    let code = reason.rawValue
    report(info, payload: payload, fromPushKit: true) {
      RNCallKeep.endCall(withUUID: uuid, reason: code)
      completion()
    }
  }

  private func handleDismiss(
    _ info: CallPushInfo,
    payload: [AnyHashable: Any],
    viaPushKit: Bool,
    completion: @escaping () -> Void
  ) {
    let reason = LotusCallPushRouter.endReason(for: info)
    cancelRingTimeout(info.callUUID)

    guard let call = systemCall(matching: info) else {
      if let uuid = rememberedRingUUID(for: info) {
        // Reported to CallKit moments ago; CXCallObserver has not caught up. End it
        // anyway — ending a UUID CallKit already dropped is harmless.
        NSLog("[LotusCallPush] %@ for %@ — ending just-reported ring %@", info.type, info.callId, uuid)
        cancelRingTimeout(uuid)
        RNCallKeep.endCall(withUUID: uuid, reason: reason.rawValue)
      } else {
        // Nothing ringing here: already answered or timed out, or the ring has not
        // arrived yet.
        NSLog("[LotusCallPush] %@ for %@ — no system call", info.type, info.callId)
      }
      // Either way, a ring push that lands after this dismiss must not ring.
      rememberDismissal(info, reason: reason)
      if viaPushKit {
        reportAndEnd(info, payload: payload, reason: reason, completion: completion)
      } else {
        completion()
      }
      return
    }

    let uuid = call.uuid.uuidString.lowercased()
    cancelRingTimeout(uuid)

    if call.hasConnected {
      // Answered on this device: JS owns the media session; a dismiss never tears it down natively.
      NSLog("[LotusCallPush] %@ for %@ — connected here, leaving it to JS", info.type, info.callId)
      if viaPushKit {
        // Rejected as a duplicate UUID: satisfies PushKit, changes nothing on screen.
        report(info, uuid: uuid, payload: payload, fromPushKit: true, completion: completion)
      } else {
        completion()
      }
      return
    }

    NSLog("[LotusCallPush] %@ for %@ — ending ring %@ (reason %d)", info.type, info.callId, uuid, reason.rawValue)
    let code = reason.rawValue
    if viaPushKit {
      // Re-reporting the ringing UUID is rejected (CallUUIDAlreadyExists) — still a report
      // for PushKit's purposes, and it never shows a second UI. Then end the real ring.
      report(info, uuid: uuid, payload: payload, fromPushKit: true) {
        RNCallKeep.endCall(withUUID: uuid, reason: code)
        completion()
      }
    } else {
      RNCallKeep.endCall(withUUID: uuid, reason: code)
      completion()
    }
  }

  // MARK: Entry points

  /// PushKit. The completion reaches CallKit exactly once.
  func handleVoipPush(_ payload: [AnyHashable: Any], completion: @escaping () -> Void) {
    guard let info = LotusCallPushRouter.parse(payload, defaultType: "INCOMING_CALL") else {
      // Unparseable VoIP push: CallKit is still owed a report. Report a placeholder and end it at once.
      let uuid = UUID().uuidString.lowercased()
      NSLog("[LotusCallPush] VoIP push without a callId — reporting placeholder %@", uuid)
      RNCallKeep.reportNewIncomingCall(
        uuid,
        handle: "lotus-call",
        handleType: "generic",
        hasVideo: false,
        localizedCallerName: "Lotus Caller",
        supportsHolding: false,
        supportsDTMF: false,
        supportsGrouping: false,
        supportsUngrouping: false,
        fromPushKit: true,
        payload: payload
      ) {
        RNCallKeep.endCall(withUUID: uuid, reason: EndReason.failed.rawValue)
        completion()
      }
      return
    }

    if LotusCallPushRouter.isDismissType(info.type) {
      handleDismiss(info, payload: payload, viaPushKit: true, completion: completion)
      return
    }

    if let reason = dismissalPreceding(info) {
      NSLog("[LotusCallPush] %@ was dismissed before its ring arrived — not ringing", info.callId)
      reportAndEnd(info, payload: payload, reason: reason, completion: completion)
      return
    }

    if let existing = systemCall(matching: info) {
      // Duplicate ring (backend retry, or the APNs fallback racing PushKit). CallKit rejects
      // the re-report as CallUUIDAlreadyExists — still the report PushKit requires — and the
      // original ring timeout keeps running, so a retry can never stretch the ring.
      NSLog("[LotusCallPush] %@ already %@ — duplicate ring push", info.callId, existing.hasConnected ? "connected" : "ringing")
      report(info, uuid: existing.uuid.uuidString.lowercased(), payload: payload, fromPushKit: true, completion: completion)
      return
    }

    if let sentAt = info.sentAt, Date().timeIntervalSince(sentAt) > LotusCallPushRouter.stalePushThresholdSeconds {
      NSLog("[LotusCallPush] stale ring for %@ (sent %.0fs ago) — logged as missed, not ringing", info.callId, Date().timeIntervalSince(sentAt))
      reportAndEnd(info, payload: payload, reason: .unanswered, completion: completion)
      return
    }

    NSLog("[LotusCallPush] ringing %@ as %@", info.callId, info.callUUID)
    ring(info, payload: payload, fromPushKit: true, completion: completion)
  }

  /// Non-VoIP APNs. True when this was a CALL_DISMISS / MISSED_CALL (the ring was ended here).
  func handleRemoteDismissIfNeeded(_ userInfo: [AnyHashable: Any]) -> Bool {
    guard let info = LotusCallPushRouter.parse(userInfo, defaultType: nil),
          LotusCallPushRouter.isDismissType(info.type) else {
      return false
    }
    handleDismiss(info, payload: userInfo, viaPushKit: false) {}
    return true
  }

  /// Non-VoIP APNs INCOMING_CALL fallback. False when this is not a ring push.
  func handleRemoteIncomingCall(_ userInfo: [AnyHashable: Any], completion: @escaping () -> Void) -> Bool {
    guard let info = LotusCallPushRouter.parse(userInfo, defaultType: nil), info.type == "INCOMING_CALL" else {
      return false
    }
    if systemCall(matching: info) != nil {
      // PushKit already delivered this ring (or it was answered): nothing to add.
      NSLog("[LotusCallPush] %@ already known to CallKit — APNs ring ignored", info.callId)
      completion()
      return true
    }
    if dismissalPreceding(info) != nil {
      NSLog("[LotusCallPush] %@ was dismissed before its APNs ring arrived — ignored", info.callId)
      completion()
      return true
    }
    if let sentAt = info.sentAt, Date().timeIntervalSince(sentAt) > LotusCallPushRouter.stalePushThresholdSeconds {
      NSLog("[LotusCallPush] stale APNs ring for %@ (sent %.0fs ago) — ignored", info.callId, Date().timeIntervalSince(sentAt))
      completion()
      return true
    }
    NSLog("[LotusCallPush] ringing (APNs fallback) %@ as %@", info.callId, info.callUUID)
    ring(info, payload: userInfo, fromPushKit: false, completion: completion)
    return true
  }
}

// MARK: - Lotus call API
//
// Tells the backend "this device is ringing" and "declined" from native code — the same
// endpoints JS calls — so they arrive with the JS runtime suspended or not yet started.
//
// Requests go through CertificateModule's shared mTLS session, so they carry the client
// certificate and the session cookies in HTTPCookieStorage.shared. The backend authenticates
// those cookies exactly as it does for the dashboard (renewing an expired token from the
// session cookie), so no token is copied into native storage.
enum LotusCallApi {
  /// Waits between attempts: five tries across ~15 s. That rides out a radio still waking up,
  /// and stays inside both iOS's background-time grant and the 30 s the call rings for —
  /// after which the server no longer accepts a decline.
  private static let retryDelaysSeconds: [TimeInterval] = [1, 2, 4, 8]
  /// performMtlsRequest's rejections when this install has no client certificate (mTLS off).
  private static let missingIdentityCodes: Set<String> = ["NO_PRIVATE_KEY", "NO_CERTIFICATE", "NO_IDENTITY"]

  static func reportRingStatus(callId: String, busy: Bool) {
    post(callId: callId, action: "ring-status", body: ["ringStatus": busy ? "BUSY" : "RINGING"])
  }

  static func decline(callId: String) {
    post(callId: callId, action: "decline", body: [:])
  }

  /// Written to Info.plist by this plugin from the value JS uses (extra.lotusApiBaseUrl).
  private static var baseURL: String? {
    guard let raw = Bundle.main.object(forInfoDictionaryKey: "LotusApiBaseUrl") as? String else {
      return nil
    }
    let trimmed = raw.trimmingCharacters(in: CharacterSet(charactersIn: "/ "))
    return trimmed.isEmpty ? nil : trimmed
  }

  private static func post(callId: String, action: String, body: [String: Any]) {
    var idCharacters = CharacterSet.alphanumerics
    idCharacters.insert(charactersIn: "-._~")
    guard let base = baseURL,
          let encodedId = callId.addingPercentEncoding(withAllowedCharacters: idCharacters),
          let data = try? JSONSerialization.data(withJSONObject: body),
          let payload = String(data: data, encoding: .utf8) else {
      NSLog("[LotusCallApi] %@", "\\(action) for \\(callId) skipped — no API base URL in Info.plist")
      return
    }
    // Keeps the process running until the request settles, even once CallKit's UI is gone.
    let backgroundTime = LotusBackgroundTime(name: "lotus-call-\\(action)")
    attempt(1, url: "\\(base)/calls/\\(encodedId)/\\(action)", payload: payload, label: "\\(action) \\(callId)") {
      backgroundTime.end()
    }
  }

  private static func attempt(
    _ number: Int,
    url: String,
    payload: String,
    label: String,
    done: @escaping () -> Void
  ) {
    send(url: url, payload: payload) { status in
      let outcome = status == 0 ? "no response" : String(status)
      NSLog("[LotusCallApi] %@", "\\(label): attempt \\(number) -> \\(outcome)")
      // No answer, a timeout / rate limit or a server error is worth another try. Anything
      // else — success, or a 4xx such as "not signed in" — is the server's final word.
      let retryable = status == 0 || status == 408 || status == 429 || status >= 500
      guard retryable, number <= retryDelaysSeconds.count else {
        done()
        return
      }
      DispatchQueue.main.asyncAfter(deadline: .now() + retryDelaysSeconds[number - 1]) {
        attempt(number + 1, url: url, payload: payload, label: label, done: done)
      }
    }
  }

  /// Completes with the HTTP status, or 0 when the request never got an answer.
  private static func send(url: String, payload: String, completion: @escaping (Int) -> Void) {
    let headers = [
      "Content-Type": "application/json",
      "x-platform": "native",
      "x-request-id": UUID().uuidString.lowercased()
    ]
    CertificateModule().performMtlsRequest(
      url,
      requestId: nil,
      method: "POST",
      headers: headers as NSDictionary,
      body: payload,
      resolve: { result in
        completion(((result as? [String: Any])?["status"] as? Int) ?? 0)
      },
      reject: { code, _, _ in
        guard let code = code, missingIdentityCodes.contains(code), let target = URL(string: url) else {
          completion(0)
          return
        }
        // No client certificate on this install: the plain session sends the same cookies.
        var request = URLRequest(url: target)
        request.httpMethod = "POST"
        request.httpBody = payload.data(using: .utf8)
        headers.forEach { request.setValue($0.value, forHTTPHeaderField: $0.key) }
        URLSession.shared.dataTask(with: request) { _, response, _ in
          completion((response as? HTTPURLResponse)?.statusCode ?? 0)
        }.resume()
      }
    )
  }
}

/// Background execution time from UIKit that is safe to end more than once.
final class LotusBackgroundTime {
  private var task: UIBackgroundTaskIdentifier = .invalid

  init(name: String) {
    task = UIApplication.shared.beginBackgroundTask(withName: name) { [weak self] in
      self?.end()
    }
  }

  func end() {
    DispatchQueue.main.async {
      guard self.task != .invalid else {
        return
      }
      UIApplication.shared.endBackgroundTask(self.task)
      self.task = .invalid
    }
  }
}
`;

function resolveProjectName(config) {
  const fromModRequest = config?.modRequest?.projectName;
  if (fromModRequest) {
    return fromModRequest;
  }

  const iosDir = path.join(config.modRequest.projectRoot, 'ios');
  if (!fs.existsSync(iosDir)) {
    return null;
  }

  const xcodeproj = fs.readdirSync(iosDir).find(entry => entry.endsWith('.xcodeproj'));

  if (!xcodeproj) {
    return null;
  }

  return xcodeproj.replace(/\.xcodeproj$/, '');
}


function ensureRemoteNotificationFallback(contents) {
  if (contents.includes('didReceiveRemoteNotification userInfo')) {
    if (!contents.includes('router.handleRemoteDismissIfNeeded(userInfo)')) {
      throw new Error(
        `[${PLUGIN_NAME}] AppDelegate.swift's didReceiveRemoteNotification ${STALE_APPDELEGATE_HINT}`,
      );
    }
    return contents;
  }

  const marker = '  // Universal Links\n';
  if (!contents.includes(marker)) {
    return contents;
  }

  const fallbackMethod = `  public override func application(
    _ application: UIApplication,
    didReceiveRemoteNotification userInfo: [AnyHashable: Any],
    fetchCompletionHandler completionHandler: @escaping (UIBackgroundFetchResult) -> Void
  ) {
    let router = LotusCallPushRouter.shared

    // CALL_DISMISS / MISSED_CALL: end the CallKit ring natively (works while JS is
    // suspended), then let RN Firebase / Expo see the push as before for JS bookkeeping.
    if router.handleRemoteDismissIfNeeded(userInfo) {
      super.application(application, didReceiveRemoteNotification: userInfo, fetchCompletionHandler: completionHandler)
      return
    }

    let completionLock = NSLock()
    var didComplete = false
    let completeOnce: (UIBackgroundFetchResult) -> Void = { result in
      completionLock.lock()
      defer { completionLock.unlock() }
      guard !didComplete else { return }
      didComplete = true
      completionHandler(result)
    }

    // INCOMING_CALL over plain APNs (VoIP fallback): ring through the same router.
    if router.handleRemoteIncomingCall(userInfo, completion: { completeOnce(.newData) }) {
      return
    }

    super.application(application, didReceiveRemoteNotification: userInfo, fetchCompletionHandler: completionHandler)
  }

`;

  return contents.replace(marker, `${fallbackMethod}${marker}`);
}

const ROUTER_START_MARKER = '\n// MARK: - Lotus call push router (generated by with-voip-push-ios)';
const DELEGATE_MARKER = '\nclass ReactNativeDelegate: ExpoReactNativeFactoryDelegate {';

/**
 * Inserts LotusCallPushRouter (top-level type) ahead of ReactNativeDelegate.
 * A block generated by an earlier plugin version is replaced in place, so a
 * prebuild without --clean still ships the current router.
 */
function ensureCallPushRouter(contents) {
  const start = contents.indexOf(ROUTER_START_MARKER);
  if (start !== -1) {
    const end = contents.indexOf(DELEGATE_MARKER, start);
    if (end === -1) {
      throw new Error(
        `[${PLUGIN_NAME}] AppDelegate.swift has a LotusCallPushRouter block without ReactNativeDelegate after it. ` +
          'Run "npx expo prebuild --platform ios --clean" to regenerate it.',
      );
    }
    if (contents.slice(start, end) === CALL_PUSH_ROUTER_SWIFT) {
      return contents;
    }
    return `${contents.slice(0, start)}${CALL_PUSH_ROUTER_SWIFT}${contents.slice(end)}`;
  }

  if (contents.includes('final class LotusCallPushRouter')) {
    // Hand-maintained copy without the generated header: leave it alone.
    return contents;
  }

  if (contents.includes(DELEGATE_MARKER)) {
    return contents.replace(DELEGATE_MARKER, `\n${CALL_PUSH_ROUTER_SWIFT}${DELEGATE_MARKER}`);
  }

  return `${contents}\n${CALL_PUSH_ROUTER_SWIFT}`;
}

function ensurePushRegistryExtension(contents) {
  const hasSetupVoIPPush = contents.includes('private func setupVoIPPush()');
  const hasDidUpdateCredentials = contents.includes('didUpdate credentials: PKPushCredentials');
  const hasDidInvalidateToken = contents.includes('didInvalidatePushTokenFor type: PKPushType');
  const hasDidReceiveIncomingPush = contents.includes(
    'didReceiveIncomingPushWith payload: PKPushPayload',
  );

  if (
    hasDidReceiveIncomingPush &&
    !contents.includes('LotusCallPushRouter.shared.handleVoipPush')
  ) {
    throw new Error(
      `[${PLUGIN_NAME}] AppDelegate.swift's PushKit handler ${STALE_APPDELEGATE_HINT}`,
    );
  }

  if (
    hasSetupVoIPPush &&
    hasDidUpdateCredentials &&
    hasDidInvalidateToken &&
    hasDidReceiveIncomingPush
  ) {
    return contents;
  }

  const blocks = [];

  if (!hasSetupVoIPPush) {
    blocks.push(
      '  private func setupVoIPPush() {\n' +
        '    let registry = PKPushRegistry(queue: DispatchQueue.main)\n' +
        '    registry.delegate = self\n' +
        '    registry.desiredPushTypes = [.voIP]\n' +
        '    voipRegistry = registry\n' +
        '  }',
    );
  }

  if (!hasDidUpdateCredentials) {
    blocks.push(
      '  public func pushRegistry(\n' +
        '    _ registry: PKPushRegistry,\n' +
        '    didUpdate credentials: PKPushCredentials,\n' +
        '    for type: PKPushType\n' +
        '  ) {\n' +
        '    RNVoipPushNotificationManager.didUpdate(\n' +
        '      credentials,\n' +
        '      forType: type.rawValue\n' +
        '    )\n' +
        '  }',
    );
  }

  if (!hasDidInvalidateToken) {
    blocks.push(
      '  public func pushRegistry(\n' +
        '    _ registry: PKPushRegistry,\n' +
        '    didInvalidatePushTokenFor type: PKPushType\n' +
        '  ) {\n' +
        '    // Intentionally empty; server-side token cleanup is handled when needed.\n' +
        '  }',
    );
  }

  if (!hasDidReceiveIncomingPush) {
    blocks.push(
      '  public func pushRegistry(\n' +
        '    _ registry: PKPushRegistry,\n' +
        '    didReceiveIncomingPushWith payload: PKPushPayload,\n' +
        '    for type: PKPushType,\n' +
        '    completion: @escaping () -> Void\n' +
        '  ) {\n' +
        '    let payloadDict = payload.dictionaryPayload\n' +
        '\n' +
        '    // Keep the JS bridge informed (payload cache for answering, cold-start buffer).\n' +
        '    RNVoipPushNotificationManager.didReceiveIncomingPush(\n' +
        '      with: payload,\n' +
        '      forType: type.rawValue\n' +
        '    )\n' +
        '\n' +
        '    // completion reaches CallKit exactly once, via LotusCallPushRouter →\n' +
        '    // RNCallKeep.reportNewIncomingCall. Registering it with addCompletionHandler as\n' +
        "    // well made PKPushRegistry's completion fire twice (once via CallKit, once when\n" +
        '    // JS called onVoipNotificationCompleted), invalidating the VoIP Mach port while\n' +
        '    // the main run loop still held it — a crash in __CFRunLoopServiceMachPort.\n' +
        '    LotusCallPushRouter.shared.handleVoipPush(payloadDict, completion: completion)\n' +
        '  }',
    );
  }

  if (blocks.length === 0) {
    return contents;
  }

  const extensionBlock = `\nextension AppDelegate {\n${blocks.join('\n\n')}\n}\n`;

  const marker = '\nclass ReactNativeDelegate: ExpoReactNativeFactoryDelegate {';
  if (contents.includes(marker)) {
    return contents.replace(marker, `${extensionBlock}${marker}`);
  }

  return `${contents}\n${extensionBlock}`;
}


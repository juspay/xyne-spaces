// MARK: - URLSession Delegate for mTLS
private class MtlsProxySessionDelegate: NSObject, URLSessionTaskDelegate {
    private let identity: SecIdentity
    private let certificate: SecCertificate
    private let expectedHost: String
    private let serverTrustPolicy: MtlsServerTrustPolicy?
    private let allowedScheme: String
    private let allowedPort: Int
    private let allowedPathPrefix: String

    init(
        identity: SecIdentity,
        certificate: SecCertificate,
        expectedHost: String,
        serverTrustPolicy: MtlsServerTrustPolicy?,
        allowedScheme: String,
        allowedPort: Int,
        allowedPathPrefix: String
    ) {
        self.identity = identity
        self.certificate = certificate
        self.expectedHost = expectedHost
        self.serverTrustPolicy = serverTrustPolicy
        self.allowedScheme = allowedScheme
        self.allowedPort = allowedPort
        self.allowedPathPrefix = allowedPathPrefix
        super.init()
    }

    func urlSession(
        _ session: URLSession,
        task: URLSessionTask,
        willPerformHTTPRedirection response: HTTPURLResponse,
        newRequest request: URLRequest,
        completionHandler: @escaping (URLRequest?) -> Void
    ) {
        guard let redirectURL = request.url,
              isAllowedRedirect(
                  redirectURL,
                  scheme: allowedScheme,
                  host: expectedHost,
                  port: allowedPort,
                  pathPrefix: allowedPathPrefix
              ) else {
            NSLog("[MtlsProxySessionDelegate] Rejecting redirect outside the approved origin/path")
            completionHandler(nil)
            return
        }
        completionHandler(request)
    }

    func urlSession(_ session: URLSession, didReceive challenge: URLAuthenticationChallenge, completionHandler: @escaping (URLSession.AuthChallengeDisposition, URLCredential?) -> Void) {
        switch challenge.protectionSpace.authenticationMethod {
        case NSURLAuthenticationMethodClientCertificate:
            guard challenge.protectionSpace.host.lowercased() == expectedHost else {
                completionHandler(.cancelAuthenticationChallenge, nil)
                return
            }
            let credential = URLCredential(identity: identity, certificates: [certificate], persistence: .forSession)
            completionHandler(.useCredential, credential)

        case NSURLAuthenticationMethodServerTrust:
            guard let trust = challenge.protectionSpace.serverTrust,
                  let serverTrustPolicy,
                  serverTrustPolicy.evaluate(trust, challengeHost: challenge.protectionSpace.host) else {
                completionHandler(.cancelAuthenticationChallenge, nil)
                return
            }
            completionHandler(.useCredential, URLCredential(trust: trust))

        default:
            completionHandler(.performDefaultHandling, nil)
        }
    }
}

// MARK: - Streaming Delegate for Video
private class MtlsStreamingDelegate: NSObject, URLSessionDataDelegate, URLSessionDelegate {
    private let identity: SecIdentity
    private let certificate: SecCertificate
    private let connection: NWConnection
    private let expectedHost: String
    private let serverTrustPolicy: MtlsServerTrustPolicy?
    private let allowedScheme: String
    private let allowedPort: Int
    private let allowedPathPrefix: String
    private var headersSent = false
    private var pendingData: [Data] = []
    private var responseUrl: URL?
    private var dataTask: URLSessionDataTask?
    private let writeQueue = DispatchQueue(label: "com.lotus.mtlsproxy.streaming-write")
    private var queuedWrites: [Data] = []
    private var writeInFlight = false
    private var upstreamFinished = false
    private var connectionClosed = false
    private var responseStatusCode: Int?
    private var advertisedContentLength: Int64?
    private var deliveredByteCount: Int64 = 0

    init(
        identity: SecIdentity,
        certificate: SecCertificate,
        connection: NWConnection,
        request: URLRequest,
        expectedHost: String,
        serverTrustPolicy: MtlsServerTrustPolicy?,
        allowedScheme: String,
        allowedPort: Int,
        allowedPathPrefix: String
    ) {
        self.identity = identity
        self.certificate = certificate
        self.connection = connection
        self.expectedHost = expectedHost
        self.serverTrustPolicy = serverTrustPolicy
        self.allowedScheme = allowedScheme
        self.allowedPort = allowedPort
        self.allowedPathPrefix = allowedPathPrefix
        self.responseUrl = request.url
        super.init()

        let configuration = URLSessionConfiguration.default
        configuration.httpShouldSetCookies = false
        configuration.httpCookieAcceptPolicy = .never
        configuration.httpCookieStorage = nil
        configuration.timeoutIntervalForRequest = 0 // No timeout for streaming
        configuration.timeoutIntervalForResource = 0

        let session = URLSession(configuration: configuration, delegate: self, delegateQueue: .main)
        self.dataTask = session.dataTask(with: request)
        self.dataTask?.resume()
    }

    func urlSession(
        _ session: URLSession,
        task: URLSessionTask,
        willPerformHTTPRedirection response: HTTPURLResponse,
        newRequest request: URLRequest,
        completionHandler: @escaping (URLRequest?) -> Void
    ) {
        guard let redirectURL = request.url,
              isAllowedRedirect(
                  redirectURL,
                  scheme: allowedScheme,
                  host: expectedHost,
                  port: allowedPort,
                  pathPrefix: allowedPathPrefix
              ) else {
            NSLog("[MtlsStreamingDelegate] Rejecting redirect outside the approved origin/path")
            completionHandler(nil)
            return
        }
        completionHandler(request)
    }

    func urlSession(_ session: URLSession, dataTask: URLSessionDataTask, didReceive response: URLResponse, completionHandler: @escaping (URLSession.ResponseDisposition) -> Void) {
        if let httpResponse = response as? HTTPURLResponse {
            responseStatusCode = httpResponse.statusCode
            advertisedContentLength = Self.parseNonNegativeContentLength(
                httpResponse.value(forHTTPHeaderField: "Content-Length")
            )
            NSLog(
                "[MtlsStreamingDelegate] Received response: \(httpResponse.statusCode), " +
                    "content-length: \(advertisedContentLength.map(String.init) ?? "unknown")"
            )
            if let url = responseUrl {
                sendStreamingHeaders(httpResponse, url: url)
                headersSent = true
            }
        }
        completionHandler(.allow)
    }

    func urlSession(_ session: URLSession, dataTask: URLSessionDataTask, didReceive data: Data) {
        // Stream data as it arrives
        deliveredByteCount += Int64(data.count)
        if headersSent {
            sendData(data)
        } else {
            // Queue data until headers are sent
            pendingData.append(data)
        }
    }

    private func sendData(_ data: Data) {
        // Flush any pending data first
        if !pendingData.isEmpty {
            let combined = pendingData.reduce(Data()) { $0 + $1 }
            pendingData.removeAll()
            sendDataChunk(combined)
        }
        sendDataChunk(data)
    }

    private func sendDataChunk(_ data: Data) {
        guard !data.isEmpty else { return }
        writeQueue.async { [weak self] in
            guard let self, !self.connectionClosed else { return }
            self.queuedWrites.append(data)
            self.pumpWrites()
        }
    }

    private func finishWriting() {
        writeQueue.async { [weak self] in
            guard let self else { return }
            self.upstreamFinished = true
            self.pumpWrites()
        }
    }

    private func pumpWrites() {
        dispatchPrecondition(condition: .onQueue(writeQueue))
        guard !connectionClosed, !writeInFlight else { return }

        guard !queuedWrites.isEmpty else {
            if upstreamFinished {
                connectionClosed = true
                connection.cancel()
            }
            return
        }

        let next = queuedWrites.removeFirst()
        writeInFlight = true
        connection.send(content: next, completion: .contentProcessed { [weak self] error in
            guard let self else { return }
            self.writeQueue.async {
                self.writeInFlight = false
                if let error {
                    self.connectionClosed = true
                    self.queuedWrites.removeAll()
                    self.dataTask?.cancel()
                    NSLog("[MtlsStreamingDelegate] Send error: \(error)")
                    self.connection.cancel()
                    return
                }
                self.pumpWrites()
            }
        })
    }

    func urlSession(_ session: URLSession, task: URLSessionTask, didCompleteWithError error: Error?) {
        if let error = error {
            NSLog("[MtlsStreamingDelegate] Error: \(error)")
        }
        NSLog(
            "[MtlsStreamingDelegate] Completed status: \(responseStatusCode.map(String.init) ?? "unknown"), " +
                "delivered: \(deliveredByteCount), " +
                "advertised: \(advertisedContentLength.map(String.init) ?? "unknown")"
        )
        // Flush any remaining data
        if !pendingData.isEmpty {
            let combined = pendingData.reduce(Data()) { $0 + $1 }
            pendingData.removeAll()
            sendDataChunk(combined)
        }
        finishWriting()
    }

    func urlSession(_ session: URLSession, didReceive challenge: URLAuthenticationChallenge, completionHandler: @escaping (URLSession.AuthChallengeDisposition, URLCredential?) -> Void) {
        switch challenge.protectionSpace.authenticationMethod {
        case NSURLAuthenticationMethodClientCertificate:
            guard challenge.protectionSpace.host.lowercased() == expectedHost else {
                completionHandler(.cancelAuthenticationChallenge, nil)
                return
            }
            let credential = URLCredential(identity: identity, certificates: [certificate], persistence: .forSession)
            completionHandler(.useCredential, credential)
        case NSURLAuthenticationMethodServerTrust:
            guard let trust = challenge.protectionSpace.serverTrust,
                  let serverTrustPolicy,
                  serverTrustPolicy.evaluate(trust, challengeHost: challenge.protectionSpace.host) else {
                completionHandler(.cancelAuthenticationChallenge, nil)
                return
            }
            completionHandler(.useCredential, URLCredential(trust: trust))
        default:
            completionHandler(.performDefaultHandling, nil)
        }
    }

    private func sendStreamingHeaders(_ response: HTTPURLResponse, url: URL) {
        NSLog("[MtlsStreamingDelegate] Sending headers for status: \(response.statusCode)")

        var responseStr = "HTTP/1.1 \(response.statusCode) \(HTTPURLResponse.localizedString(forStatusCode: response.statusCode))\r\n"

        let responseHeaders = response.allHeaderFields.reduce(into: [String: (name: String, value: String)]()) { headers, entry in
            guard let key = entry.key as? String else { return }
            headers[key.lowercased()] = (key, "\(entry.value)")
        }
        let contentEncoding = responseHeaders["content-encoding"]?.value
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased()
        let canForwardContentLength = contentEncoding == nil || contentEncoding == "identity"

        // Collect content-type and preserve framing only when the body is not
        // encoded differently from the advertised upstream representation.
        var contentType: String?
        var hasContentLength = false
        var hasAcceptRanges = false
        var validatedContentRange: String?
        for lowerKey in ["content-type", "content-length", "accept-ranges", "content-range", "etag", "last-modified"] {
            guard let header = responseHeaders[lowerKey] else { continue }
            if lowerKey == "content-length" {
                guard canForwardContentLength,
                      let contentLength = Self.parseNonNegativeContentLength(header.value) else {
                    continue
                }
                responseStr += "\(header.name): \(contentLength)\r\n"
                hasContentLength = true
            } else if lowerKey == "content-range" {
                guard let contentRange = Self.validateContentRange(header.value, statusCode: response.statusCode) else {
                    continue
                }
                responseStr += "\(header.name): \(contentRange)\r\n"
                validatedContentRange = contentRange
            } else {
                responseStr += "\(header.name): \(header.value)\r\n"
            }

            if lowerKey == "content-type" {
                contentType = header.value
            } else if lowerKey == "accept-ranges" {
                hasAcceptRanges = true
            }
        }

        // A ranged response can still be framed safely when the origin omits
        // Content-Length: the inclusive byte range gives us the exact body
        // size delivered to AVPlayer.
        if !hasContentLength,
           canForwardContentLength,
           response.statusCode == 206,
           let contentRange = validatedContentRange {
            let rangeParts = contentRange.split(separator: " ", maxSplits: 1)
            if rangeParts.count == 2,
               rangeParts[0].lowercased() == "bytes",
               let byteRange = rangeParts.last,
               let rangeBounds = byteRange.split(separator: "/", maxSplits: 1).first {
                let bounds = rangeBounds.split(separator: "-", maxSplits: 1).compactMap({ Int64($0) })
                if bounds.count == 2, bounds[0] >= 0, bounds[1] >= bounds[0] {
                    let (rangeLength, rangeOverflow) = bounds[1].subtractingReportingOverflow(bounds[0])
                    let (contentLength, lengthOverflow) = rangeLength.addingReportingOverflow(1)
                    if !rangeOverflow && !lengthOverflow {
                        responseStr += "Content-Length: \(contentLength)\r\n"
                        hasContentLength = true
                    }
                }
            }
        }

        // Ensure Content-Type is set (critical for AVPlayer)
        if contentType == nil {
            // Guess only for successful media responses. Error bodies must not
            // be labelled as video or AVPlayer reports an opaque parse error.
            if (200..<300).contains(response.statusCode) &&
               (url.path.hasSuffix(".mp4") || url.path.contains("/stream")) {
                responseStr += "Content-Type: video/mp4\r\n"
            } else if (200..<300).contains(response.statusCode) && url.path.hasSuffix(".mov") {
                responseStr += "Content-Type: video/quicktime\r\n"
            } else if (200..<300).contains(response.statusCode) && url.path.hasSuffix(".m4v") {
                responseStr += "Content-Type: video/x-m4v\r\n"
            } else {
                responseStr += "Content-Type: text/plain; charset=utf-8\r\n"
            }
        }

        if !hasAcceptRanges {
            responseStr += "Accept-Ranges: bytes\r\n"
        }
        responseStr += "Connection: close\r\n\r\n"

        NSLog("[MtlsStreamingDelegate] Headers: \(responseStr)")

        if let data = responseStr.data(using: .utf8) {
            sendDataChunk(data)
        }
    }

    private static func parseNonNegativeContentLength(_ value: String?) -> Int64? {
        guard let value,
              !value.isEmpty,
              value.allSatisfy({ $0.isASCII && $0.isNumber }),
              let parsed = Int64(value) else {
            return nil
        }
        return parsed
    }

    private static func validateContentRange(_ value: String, statusCode: Int) -> String? {
        let parts = value.split(separator: " ", maxSplits: 1, omittingEmptySubsequences: true)
        guard parts.count == 2, parts[0].lowercased() == "bytes" else { return nil }

        let rangeAndTotal = parts[1].split(separator: "/", maxSplits: 1, omittingEmptySubsequences: false)
        guard rangeAndTotal.count == 2 else { return nil }
        let range = rangeAndTotal[0]
        let total = rangeAndTotal[1]

        if range == "*" {
            guard statusCode == 416,
                  Self.parseNonNegativeContentLength(String(total)) != nil else {
                return nil
            }
            return "bytes */\(total)"
        }

        guard statusCode == 206 else { return nil }
        let bounds = range.split(separator: "-", maxSplits: 1, omittingEmptySubsequences: false)
        guard bounds.count == 2,
              let start = Int64(bounds[0]),
              let end = Int64(bounds[1]),
              start >= 0,
              end >= start else {
            return nil
        }

        if total != "*" {
            guard let totalLength = Self.parseNonNegativeContentLength(String(total)) else {
                return nil
            }
            let minimumTotal = end.addingReportingOverflow(1)
            guard !minimumTotal.overflow, totalLength >= minimumTotal.partialValue else { return nil }
        }

        return "bytes \(start)-\(end)/\(total)"
    }
}

import Foundation
import Network
import Security

private struct MtlsServerTrustPolicy {
    let expectedHost: String

    init?(expectedHost: String) {
        let normalizedHost = expectedHost.lowercased()
        guard !normalizedHost.isEmpty else { return nil }
        self.expectedHost = normalizedHost
    }

    func evaluate(_ trust: SecTrust, challengeHost: String) -> Bool {
        guard challengeHost.lowercased() == expectedHost else { return false }

        // Validate the server against the platform trust store, while making
        // the exact expected hostname explicit. Never accept a presented trust
        // object without evaluation.
        let sslPolicy = SecPolicyCreateSSL(true, expectedHost as CFString)
        guard SecTrustSetPolicies(trust, sslPolicy) == errSecSuccess else {
            return false
        }

        var error: CFError?
        return SecTrustEvaluateWithError(trust, &error)
    }
}

private func isAllowedRedirect(
    _ url: URL,
    scheme: String,
    host: String,
    port: Int,
    pathPrefix: String
) -> Bool {
    guard let components = URLComponents(url: url, resolvingAgainstBaseURL: false),
          components.scheme?.lowercased() == scheme,
          components.host?.lowercased() == host,
          (components.port ?? (scheme == "https" ? 443 : 80)) == port,
          components.user == nil,
          components.password == nil,
          components.fragment == nil else {
        return false
    }

    let path = components.percentEncodedPath
    return path.hasPrefix(pathPrefix) &&
        !path.contains("..") &&
        !path.localizedCaseInsensitiveContains("%2e") &&
        !path.localizedCaseInsensitiveContains("%2f") &&
        !path.localizedCaseInsensitiveContains("%5c")
}

/// Local HTTP proxy server that forwards requests to backend with mTLS
@objc(MtlsProxyServer)
class MtlsProxyServer: NSObject {

    private struct ProxyPolicy: Equatable {
        let scheme: String
        let host: String
        let port: Int
        let pathPrefix: String
    }

    private struct ProxySessionSnapshot {
        let capability: String
        let authToken: String?
        let listenerGeneration: UInt64
        let currentPort: UInt16
        let isRunning: Bool
    }

    private var listener: NWListener?
    private var currentPort: UInt16 = 18080
    private var isRunning = false
    private var policy: ProxyPolicy?
    private var capability = MtlsProxyServer.makeCapability()
    private var listenerGeneration: UInt64 = 0
    private let sessionStateLock = NSLock()
    private var authToken: String?

    // Headers to forward from client to backend
    private let forwardRequestHeaders: Set<String> = [
        "range", "accept", "accept-encoding", "accept-language",
        "cache-control", "connection", "user-agent", "content-type",
        "content-length", "authorization"
    ]

    // Headers to forward from backend to client
    private let forwardResponseHeaders: Set<String> = [
        "content-type", "content-length", "content-range", "accept-ranges",
        "etag", "last-modified", "cache-control", "expires"
    ]

    @objc(sharedInstance)
    static let shared = MtlsProxyServer()

    private override init() {
        super.init()
    }

    private static func makeCapability() -> String {
        var bytes = [UInt8](repeating: 0, count: 32)
        guard SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes) == errSecSuccess else {
            // UUID is still cryptographically generated by the system and keeps the
            // proxy fail-closed if the direct random provider is unavailable.
            return UUID().uuidString.replacingOccurrences(of: "-", with: "")
        }
        return Data(bytes)
            .base64EncodedString()
            .replacingOccurrences(of: "+", with: "-")
            .replacingOccurrences(of: "/", with: "_")
            .replacingOccurrences(of: "=", with: "")
    }

    private func makePolicy(allowedBaseURL: String) -> ProxyPolicy? {
        guard let url = URL(string: allowedBaseURL),
              let scheme = url.scheme?.lowercased(),
              scheme == "https" || (scheme == "http" && Self.isLoopbackHost(url.host)),
              let host = url.host?.lowercased(),
              !host.isEmpty,
              url.user == nil,
              url.password == nil,
              url.query == nil,
              url.fragment == nil else {
            return nil
        }

        let path = url.path.trimmingCharacters(in: CharacterSet(charactersIn: "/"))
        guard !path.isEmpty else { return nil }
        return ProxyPolicy(
            scheme: scheme,
            host: host,
            port: url.port ?? (scheme == "https" ? 443 : 80),
            pathPrefix: "/\(path)/attachments/"
        )
    }

    private static func isLoopbackHost(_ host: String?) -> Bool {
        host?.lowercased() == "localhost" || host == "127.0.0.1" || host == "::1"
    }

    /// Start the proxy server
    @objc
    func start(
        on port: UInt16,
        allowedBaseURL: String,
        completion: @escaping (Bool, UInt16, Error?) -> Void
    ) {
        NSLog("[MtlsProxyServer] Starting on port \(port)...")

        guard let requestedPolicy = makePolicy(allowedBaseURL: allowedBaseURL) else {
            completion(false, 0, NSError(
                domain: "MtlsProxyServer",
                code: 1,
                userInfo: [NSLocalizedDescriptionKey: "Proxy API base URL is invalid"]
            ))
            return
        }

        sessionStateLock.lock()
        let alreadyRunning = isRunning
        let activePolicy = policy
        let activePort = currentPort
        sessionStateLock.unlock()

        guard !alreadyRunning else {
            guard activePolicy == requestedPolicy else {
                completion(false, 0, NSError(
                    domain: "MtlsProxyServer",
                    code: 2,
                    userInfo: [NSLocalizedDescriptionKey: "Proxy policy cannot change while running"]
                ))
                return
            }
            NSLog("[MtlsProxyServer] Already running on port \(activePort)")
            completion(true, activePort, nil)
            return
        }

        // A previous start may still be waiting for its listener to become
        // ready after the JS-side timeout. Cancel it before replacing the
        // listener so it cannot continue listening in the background.
        sessionStateLock.lock()
        listenerGeneration &+= 1
        let generation = listenerGeneration
        capability = Self.makeCapability()
        let previousListener = listener
        listener = nil
        policy = requestedPolicy
        sessionStateLock.unlock()
        previousListener?.cancel()

        let nwPort: NWEndpoint.Port = port == 0 ? .any : NWEndpoint.Port(integerLiteral: port)
        let requestedPortLabel = port == 0 ? "ephemeral" : String(port)
        NSLog("[MtlsProxyServer] Binding loopback listener on port \(requestedPortLabel)...")

        do {
            let parameters = NWParameters.tcp
            // `requiredLocalEndpoint` already carries the port. Passing the
            // same port again through `NWListener(using:on:)` makes Network
            // reject the listener with POSIX error 22 (Invalid argument) on
            // iOS. Use the parameters-only initializer so the listener binds
            // exactly to this loopback endpoint.
            parameters.requiredLocalEndpoint = .hostPort(host: "127.0.0.1", port: nwPort)
            parameters.acceptLocalOnly = true
            let newListener = try NWListener(using: parameters)
            sessionStateLock.lock()
            guard listenerGeneration == generation else {
                sessionStateLock.unlock()
                newListener.cancel()
                return
            }
            listener = newListener
            sessionStateLock.unlock()
            NSLog("[MtlsProxyServer] NWListener created successfully")

            newListener.stateUpdateHandler = { [weak self, weak newListener] state in
                guard let self, let newListener else { return }
                var completionResult: (Bool, UInt16, Error?)?
                self.sessionStateLock.lock()
                if self.listenerGeneration == generation {
                    switch state {
                    case .setup:
                        NSLog("[MtlsProxyServer] State: setup")
                    case .waiting(let error):
                        NSLog("[MtlsProxyServer] State: waiting - \(error)")
                    case .ready:
                        if let actualPort = newListener.port?.rawValue {
                            self.currentPort = actualPort
                            self.isRunning = true
                            NSLog("[MtlsProxyServer] Started successfully on port \(actualPort)")
                            completionResult = (true, actualPort, nil)
                        }
                    case .failed(let error):
                        NSLog("[MtlsProxyServer] Failed to start: \(error)")
                        self.isRunning = false
                        completionResult = (false, 0, error)
                    case .cancelled:
                        NSLog("[MtlsProxyServer] State: cancelled")
                        self.isRunning = false
                    @unknown default:
                        NSLog("[MtlsProxyServer] State: unknown")
                    }
                }
                self.sessionStateLock.unlock()

                if let completionResult {
                    completion(completionResult.0, completionResult.1, completionResult.2)
                }
            }

            newListener.newConnectionHandler = { [weak self] connection in
                guard let self, self.isCurrentListenerGeneration(generation) else {
                    connection.cancel()
                    return
                }
                self.handleConnection(connection)
            }

            // Use a concurrent queue for better performance with multiple connections
            let listenerQueue = DispatchQueue(label: "com.lotus.mtlsproxy.listener", qos: .userInitiated, attributes: .concurrent)
            newListener.start(queue: listenerQueue)
        } catch {
            NSLog("[MtlsProxyServer] Failed to create NWListener: \(error)")
            completion(false, 0, error)
            return
        }
    }

    /// Stop the proxy server
    @objc
    func stop() {
        sessionStateLock.lock()
        listenerGeneration &+= 1
        capability = Self.makeCapability()
        authToken = nil
        isRunning = false
        policy = nil
        let listenerToCancel = listener
        listener = nil
        sessionStateLock.unlock()
        listenerToCancel?.cancel()
        NSLog("[MtlsProxyServer] Stopped")
    }

    /// Keep the bearer only in process memory for the current proxy session.
    /// It is injected only after the target has passed the exact origin/path
    /// allowlist and is cleared whenever the proxy stops.
    func setAuthToken(_ token: String?) {
        sessionStateLock.lock()
        defer { sessionStateLock.unlock() }
        authToken = token?.isEmpty == false ? token : nil
    }

    private func sessionSnapshot() -> ProxySessionSnapshot {
        sessionStateLock.lock()
        defer { sessionStateLock.unlock() }
        return ProxySessionSnapshot(
            capability: capability,
            authToken: authToken,
            listenerGeneration: listenerGeneration,
            currentPort: currentPort,
            isRunning: isRunning
        )
    }

    private func isCurrentListenerGeneration(_ generation: UInt64) -> Bool {
        sessionStateLock.lock()
        defer { sessionStateLock.unlock() }
        return listenerGeneration == generation
    }

    private func isCurrentSession(_ snapshot: ProxySessionSnapshot) -> Bool {
        sessionStateLock.lock()
        defer { sessionStateLock.unlock() }
        return isRunning &&
            listenerGeneration == snapshot.listenerGeneration &&
            capability == snapshot.capability
    }

    /// Get the current proxy port
    @objc
    func getPort() -> UInt16 {
        sessionStateLock.lock()
        defer { sessionStateLock.unlock() }
        return isRunning ? currentPort : 0
    }

    /// Build a proxied URL for the given backend URL
    @objc(getProxiedUrl:)
    func getProxiedUrl(_ backendUrl: String) -> String? {
        let session = sessionSnapshot()
        guard session.isRunning, isAllowedTarget(backendUrl) else { return nil }
        var components = URLComponents()
        components.scheme = "http"
        components.host = "127.0.0.1"
        components.port = Int(session.currentPort)
        components.path = "/proxy"
        components.queryItems = [
            URLQueryItem(name: "url", value: backendUrl),
            URLQueryItem(name: "capability", value: session.capability),
        ]
        return components.url?.absoluteString
    }

    private func handleConnection(_ connection: NWConnection) {
        let connectionQueue = DispatchQueue(label: "com.lotus.mtlsproxy.connection.\(connection.endpoint)", qos: .userInitiated)
        connection.start(queue: connectionQueue)
        NSLog("[MtlsProxyServer] New connection from \(connection.endpoint)")

        receiveHTTPRequest(connection) { [weak self] request in
            guard let self = self else {
                NSLog("[MtlsProxyServer] Connection handler deallocated")
                connection.cancel()
                return
            }

            guard let request = request else {
                NSLog("[MtlsProxyServer] Failed to parse HTTP request")
                self.sendErrorResponse(connection, status: 400, message: "Bad Request")
                return
            }

            let requestRoute = request.path.split(separator: "?", maxSplits: 1, omittingEmptySubsequences: false).first.map(String.init) ?? ""
            NSLog("[MtlsProxyServer] Received request: \(request.method) \(requestRoute)")
            self.handleProxyRequest(request, connection: connection)
        }
    }

    private func receiveHTTPRequest(_ connection: NWConnection, completion: @escaping (HTTPRequest?) -> Void) {
        var buffer = Data()
        var pendingRequest: HTTPRequest?
        var contentLength: Int = 0
        var headerEndOffset: Int = 0
        let startTime = Date()

        func receive() {
            connection.receive(minimumIncompleteLength: 1, maximumLength: 65536) { data, _, isComplete, error in
                let elapsed = Date().timeIntervalSince(startTime)

                if let error = error {
                    NSLog("[MtlsProxyServer] Receive error after %.2fs: \(error)", elapsed)
                    completion(nil)
                    return
                }

                if let data = data {
                    buffer.append(data)
                    NSLog("[MtlsProxyServer] Received \(data.count) bytes (total: \(buffer.count)) after %.2fs", elapsed)

                    // Parse headers if not yet done
                    if pendingRequest == nil {
                        if let range = buffer.range(of: Data("\r\n\r\n".utf8)) {
                            let headerData = buffer[..<range.upperBound]
                            NSLog("[MtlsProxyServer] Found header boundary, parsing...")
                            if let request = self.parseHTTPRequest(Data(headerData)) {
                                pendingRequest = request
                                contentLength = request.headers["content-length"].flatMap(Int.init) ?? 0
                                headerEndOffset = range.upperBound
                                let requestRoute = request.path.split(separator: "?", maxSplits: 1, omittingEmptySubsequences: false).first.map(String.init) ?? ""
                                NSLog("[MtlsProxyServer] Parsed request: \(request.method) \(requestRoute), content-length: \(contentLength)")
                            } else {
                                NSLog("[MtlsProxyServer] Failed to parse HTTP request from headers")
                                completion(nil)
                                return
                            }
                        }
                    }

                    // Check if body is complete
                    if let request = pendingRequest {
                        let bodyReceived = buffer.count - headerEndOffset
                        if bodyReceived >= contentLength {
                            var completeRequest = request
                            completeRequest.body = buffer.subdata(in: headerEndOffset..<(headerEndOffset + contentLength))
                            NSLog("[MtlsProxyServer] Body complete: \(contentLength) bytes received")
                            completion(completeRequest)
                            return
                        }
                    }
                }

                if isComplete {
                    NSLog("[MtlsProxyServer] Connection closed after %.2fs, buffer: \(buffer.count) bytes", elapsed)
                    completion(nil)
                    return
                }

                // Timeout after 60 seconds for large uploads
                if elapsed > 60 {
                    NSLog("[MtlsProxyServer] Receive timeout after %.2fs", elapsed)
                    completion(nil)
                    return
                }

                receive()
            }
        }

        receive()
    }

    private func parseHTTPRequest(_ data: Data) -> HTTPRequest? {
        guard let str = String(data: data, encoding: .utf8) else { return nil }
        let lines = str.split(separator: "\r\n", omittingEmptySubsequences: false)
        guard lines.count >= 1 else { return nil }

        let requestLine = lines[0].split(separator: " ")
        guard requestLine.count >= 2 else { return nil }

        let method = String(requestLine[0])
        let path = String(requestLine[1])

        var headers: [String: String] = [:]
        for i in 1..<lines.count {
            let line = lines[i]
            if line.isEmpty { break }
            let parts = line.split(separator: ":", maxSplits: 1)
            if parts.count == 2 {
                let key = String(parts[0]).lowercased().trimmingCharacters(in: .whitespaces)
                let value = String(parts[1]).trimmingCharacters(in: .whitespaces)
                headers[key] = value
            }
        }

        return HTTPRequest(method: method, path: path, headers: headers, body: Data())
    }

    private func handleProxyRequest(_ request: HTTPRequest, connection: NWConnection) {
        // Health check endpoint for testing
        if request.path == "/health" || request.path == "/" {
            let body = Data("OK".utf8)
            var response = "HTTP/1.1 200 OK\r\n"
            response += "Content-Type: text/plain\r\n"
            response += "Content-Length: \(body.count)\r\n"
            response += "Connection: close\r\n\r\n"

            if let headerData = response.data(using: .utf8) {
                connection.send(content: headerData, completion: .contentProcessed { _ in
                    connection.send(content: body, completion: .contentProcessed { _ in
                        connection.cancel()
                    })
                })
            }
            return
        }

        guard request.path == "/proxy" || request.path.hasPrefix("/proxy?") else {
            NSLog("[MtlsProxyServer] Path not found")
            sendErrorResponse(connection, status: 404, message: "Not Found")
            return
        }

        let session = sessionSnapshot()
        guard let requestCapability = extractQueryParam(from: request.path, named: "capability"),
              session.isRunning,
              constantTimeEquals(requestCapability, session.capability) else {
            sendErrorResponse(connection, status: 403, message: "Invalid proxy capability")
            return
        }

        guard let targetUrl = extractQueryParam(from: request.path, named: "url") else {
            sendErrorResponse(connection, status: 400, message: "Missing or invalid 'url' parameter")
            return
        }

        guard isAllowedTarget(targetUrl), let url = URL(string: targetUrl) else {
            sendErrorResponse(connection, status: 403, message: "Proxy target is not allowed")
            return
        }

        performMtlsRequest(url: url, originalRequest: request, connection: connection, session: session)
    }

    private func extractQueryParam(from path: String, named: String) -> String? {
        guard let queryStart = path.firstIndex(of: "?") else { return nil }
        let query = String(path[queryStart...].dropFirst())
        let pairs = query.split(separator: "&")
        for pair in pairs {
            let parts = pair.split(separator: "=", maxSplits: 1)
            if parts.count == 2, parts[0] == Substring(named) {
                return String(parts[1]).removingPercentEncoding
            }
        }
        return nil
    }

    private func isAllowedTarget(_ target: String) -> Bool {
        guard let url = URL(string: target),
              let components = URLComponents(url: url, resolvingAgainstBaseURL: false),
              let policy = currentPolicy(),
              components.scheme?.lowercased() == policy.scheme,
              components.host?.lowercased() == policy.host,
              (components.port ?? (components.scheme?.lowercased() == "https" ? 443 : 80)) == policy.port,
              components.user == nil,
              components.password == nil,
              components.fragment == nil else {
            return false
        }

        let path = components.percentEncodedPath
        return path.hasPrefix(policy.pathPrefix) &&
            !path.contains("..") &&
            !path.localizedCaseInsensitiveContains("%2e") &&
            !path.localizedCaseInsensitiveContains("%2f") &&
            !path.localizedCaseInsensitiveContains("%5c")
    }

    private func currentPolicy() -> ProxyPolicy? {
        sessionStateLock.lock()
        defer { sessionStateLock.unlock() }
        return policy
    }

    private func constantTimeEquals(_ actual: String, _ expected: String) -> Bool {
        let actualBytes = Array(actual.utf8)
        let expectedBytes = Array(expected.utf8)
        guard actualBytes.count == expectedBytes.count else { return false }
        var difference: UInt8 = 0
        for (actualByte, expectedByte) in zip(actualBytes, expectedBytes) {
            difference |= actualByte ^ expectedByte
        }
        return difference == 0
    }

    /// Snapshot only cookies scoped to the already-allowlisted upstream URL.
    /// The proxy never lets URLSession write response cookies back to the shared
    /// jar, so an in-flight request cannot repopulate auth state after logout.
    private func cookieHeader(for url: URL) -> String? {
        guard let cookies = HTTPCookieStorage.shared.cookies(for: url), !cookies.isEmpty else {
            return nil
        }
        return cookies.map { "\($0.name)=\($0.value)" }.joined(separator: "; ")
    }

    private func performMtlsRequest(
        url: URL,
        originalRequest: HTTPRequest,
        connection: NWConnection,
        session: ProxySessionSnapshot
    ) {
        NSLog("[MtlsProxyServer] Performing mTLS request to approved path: \(url.path)")

        guard isCurrentSession(session) else {
            connection.cancel()
            return
        }

        guard let identity = MtlsProxyServer.getSharedIdentity() else {
            NSLog("[MtlsProxyServer] mTLS identity not available")
            sendErrorResponse(connection, status: 503, message: "mTLS not available")
            return
        }

        guard let certificate = MtlsProxyServer.getSharedCertificate() else {
            NSLog("[MtlsProxyServer] mTLS certificate not available")
            sendErrorResponse(connection, status: 503, message: "mTLS certificate not available")
            return
        }

        NSLog("[MtlsProxyServer] mTLS credentials available, forwarding request")

        var request = URLRequest(url: url)
        request.httpMethod = originalRequest.method

        originalRequest.headers.forEach { key, value in
            if forwardRequestHeaders.contains(key) || key.hasPrefix("x-") {
                request.setValue(value, forHTTPHeaderField: key)
            }
        }

        // AVPlayer connects to localhost and cannot attach the app bearer.
        // Inject it only for this already allowlisted upstream request; never
        // accept a caller-supplied token for an unapproved target.
        if originalRequest.headers["authorization"] == nil,
           let token = session.authToken {
            request.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization")
        }

        if request.value(forHTTPHeaderField: "Cookie") == nil,
           let cookieHeader = cookieHeader(for: url) {
            request.setValue(cookieHeader, forHTTPHeaderField: "Cookie")
        }

        if ["POST", "PUT", "PATCH"].contains(originalRequest.method.uppercased()) {
            request.httpBody = originalRequest.body
        }

        // Check if this is likely a video request based on Accept header or URL
        let acceptHeader = originalRequest.headers["accept"] ?? ""
        let isVideoRequest = acceptHeader.contains("video/") || url.path.contains("/stream")

        // URLSession may transparently decompress compressed responses. Video
        // clients need the advertised length to match the bytes they receive,
        // so request the representation without content encoding.
        if isVideoRequest {
            request.setValue("identity", forHTTPHeaderField: "Accept-Encoding")
        }

        guard isCurrentSession(session) else {
            connection.cancel()
            return
        }

        guard let requestPolicy = currentPolicy(), isCurrentSession(session) else {
            connection.cancel()
            return
        }

        let expectedHost = url.host?.lowercased() ?? ""
        let serverTrustPolicy: MtlsServerTrustPolicy?
        if url.scheme?.lowercased() == "https" {
            guard let policy = MtlsServerTrustPolicy(expectedHost: expectedHost) else {
                NSLog("[MtlsProxyServer] Server trust policy unavailable for approved target")
                sendErrorResponse(connection, status: 503, message: "mTLS server trust is not configured")
                return
            }
            serverTrustPolicy = policy
        } else {
            serverTrustPolicy = nil
        }

        let delegate = MtlsProxySessionDelegate(
            identity: identity,
            certificate: certificate,
            expectedHost: expectedHost,
            serverTrustPolicy: serverTrustPolicy,
            allowedScheme: requestPolicy.scheme,
            allowedPort: requestPolicy.port,
            allowedPathPrefix: requestPolicy.pathPrefix
        )
        let configuration = URLSessionConfiguration.default
        configuration.httpShouldSetCookies = false
        configuration.httpCookieAcceptPolicy = .never
        configuration.httpCookieStorage = nil
        configuration.timeoutIntervalForRequest = 60
        configuration.timeoutIntervalForResource = 300

        let queue = OperationQueue()
        queue.maxConcurrentOperationCount = 1
        queue.qualityOfService = .utility

        // For video streaming, use streaming mode
        if isVideoRequest {
            NSLog("[MtlsProxyServer] Using streaming mode for approved video target")
            let _ = MtlsStreamingDelegate(
                identity: identity,
                certificate: certificate,
                connection: connection,
                request: request,
                expectedHost: expectedHost,
                serverTrustPolicy: serverTrustPolicy,
                allowedScheme: requestPolicy.scheme,
                allowedPort: requestPolicy.port,
                allowedPathPrefix: requestPolicy.pathPrefix
            )
            return
        }

        let session = URLSession(configuration: configuration, delegate: delegate, delegateQueue: queue)

        let task = session.dataTask(with: request) { data, response, error in
            if let error = error {
                NSLog("[MtlsProxyServer] Request error: \(error.localizedDescription)")
                self.sendErrorResponse(connection, status: 502, message: "Bad Gateway: \(error.localizedDescription)")
                return
            }

            guard let httpResponse = response as? HTTPURLResponse else {
                NSLog("[MtlsProxyServer] Invalid response type")
                self.sendErrorResponse(connection, status: 502, message: "Invalid response")
                return
            }

            NSLog("[MtlsProxyServer] Got response: \(httpResponse.statusCode), body: \(data?.count ?? 0) bytes")
            self.sendProxyResponse(connection, response: httpResponse, body: data ?? Data())
        }

        task.resume()
    }

    private func sendProxyResponse(_ connection: NWConnection, response: HTTPURLResponse, body: Data) {
        NSLog("[MtlsProxyServer] Sending response: \(response.statusCode), body: \(body.count) bytes")

        var responseStr = "HTTP/1.1 \(response.statusCode) \(HTTPURLResponse.localizedString(forStatusCode: response.statusCode))\r\n"

        // Forward whitelisted headers
        response.allHeaderFields.forEach { key, value in
            guard let keyStr = key as? String else { return }
            let lowerKey = keyStr.lowercased()
            if forwardResponseHeaders.contains(lowerKey) || lowerKey.hasPrefix("x-") {
                // Don't forward content-length if we're setting it ourselves
                if lowerKey != "content-length" {
                    responseStr += "\(keyStr): \(value)\r\n"
                }
            }
        }

        // Always send Content-Length for AVPlayer compatibility
        responseStr += "Content-Length: \(body.count)\r\n"

        // Accept-Ranges header is needed for video seeking
        if response.allHeaderFields["Accept-Ranges"] == nil {
            responseStr += "Accept-Ranges: bytes\r\n"
        }

        responseStr += "Connection: close\r\n"
        responseStr += "\r\n"

        guard let headerData = responseStr.data(using: .utf8) else {
            NSLog("[MtlsProxyServer] Failed to encode response headers")
            connection.cancel()
            return
        }

        NSLog("[MtlsProxyServer] Sending headers (\(headerData.count) bytes)")

        connection.send(content: headerData, completion: .contentProcessed { error in
            if let error = error {
                NSLog("[MtlsProxyServer] Failed to send headers: \(error)")
                connection.cancel()
                return
            }

            if body.count > 0 {
                NSLog("[MtlsProxyServer] Sending body (\(body.count) bytes)")
                connection.send(content: body, completion: .contentProcessed { error in
                    if let error = error {
                        NSLog("[MtlsProxyServer] Failed to send body: \(error)")
                    } else {
                        NSLog("[MtlsProxyServer] Response sent successfully")
                    }
                    connection.cancel()
                })
            } else {
                connection.cancel()
            }
        })
    }

    private func sendChunkedBody(_ connection: NWConnection, body: Data) {
        let chunkSize = 64 * 1024 // 64KB chunks
        var offset = 0

        func sendNextChunk() {
            let remaining = body.count - offset
            if remaining <= 0 {
                // Send final chunk
                let finalChunk = "0\r\n\r\n".data(using: .utf8)!
                connection.send(content: finalChunk, completion: .contentProcessed { _ in
                    NSLog("[MtlsProxyServer] Chunked transfer complete")
                    connection.cancel()
                })
                return
            }

            let currentChunkSize = min(chunkSize, remaining)
            let chunkData = body.subdata(in: offset..<(offset + currentChunkSize))
            let chunkHeader = String(format: "%X\r\n", currentChunkSize).data(using: .utf8)!

            var chunk = Data()
            chunk.append(chunkHeader)
            chunk.append(chunkData)
            chunk.append(Data("\r\n".utf8))

            connection.send(content: chunk, completion: .contentProcessed { error in
                if let error = error {
                    NSLog("[MtlsProxyServer] Failed to send chunk: \(error)")
                    connection.cancel()
                    return
                }
                offset += currentChunkSize
                sendNextChunk()
            })
        }

        sendNextChunk()
    }

    private func sendErrorResponse(_ connection: NWConnection, status: Int, message: String) {
        let body = "Error \(status): \(message)".data(using: .utf8) ?? Data()
        let response = """
            HTTP/1.1 \(status) Error\r\n\
            Content-Type: text/plain\r\n\
            Content-Length: \(body.count)\r\n\
            Connection: close\r\n\r\n
            """

        guard let headerData = response.data(using: .utf8) else {
            connection.cancel()
            return
        }

        connection.send(content: headerData, completion: .contentProcessed { _ in
            connection.send(content: body, completion: .contentProcessed { _ in
                connection.cancel()
            })
        })
    }

    // MARK: - Static helpers to access Keychain items

    private static let kCertificateTag = "ClientIdentity"

    static func getSharedIdentity() -> SecIdentity? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassIdentity,
            kSecAttrLabel as String: kCertificateTag,
            kSecMatchLimit as String: kSecMatchLimitOne,
            kSecReturnRef as String: true
        ]

        var item: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &item)
        guard status == errSecSuccess else { return nil }
        guard CFGetTypeID(item) == SecIdentityGetTypeID() else { return nil }
        return (item as! SecIdentity)
    }

    static func getSharedCertificate() -> SecCertificate? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassCertificate,
            kSecAttrLabel as String: kCertificateTag,
            kSecMatchLimit as String: kSecMatchLimitOne,
            kSecReturnRef as String: true
        ]

        var item: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &item)
        guard status == errSecSuccess else { return nil }
        guard CFGetTypeID(item) == SecCertificateGetTypeID() else { return nil }
        return (item as! SecCertificate)
    }
}


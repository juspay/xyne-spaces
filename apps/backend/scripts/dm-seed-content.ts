/**
 * DM seed content — Xyne Spaces local dev data.
 *
 * Direct-message conversations between people already seeded by org-seed.ts
 * (the ~100 @juspay.team accounts) plus the local dev/admin account
 * harsh.sharma.001@juspay.in. Consumed by scripts/dm-seed.ts.
 *
 * A thread is one 1:1 relationship rendered as a flat sequence of lines —
 * matching how a real DM actually reads (each message its own row in the
 * feed), not a parent+replies thread. `a` is the channel creator/ADMIN
 * participant, `b` the other side; each line picks a side with A()/B().
 *
 * Timing is authored relatively: `recency` anchors the thread's LAST message
 * to a window in the past, and each line's `gap` (minutes since the previous
 * line) walks forward from there. Omit `gap` for a natural quick-reply pace;
 * set it explicitly for a pause, an overnight gap, or a week between check-ins.
 * `hour` pins a line to a specific hour of day (0-23) for a deliberate
 * late-night or early-morning beat regardless of the natural walk.
 */

export type Side = 'a' | 'b';

export interface DmLine {
  who: Side;
  text: string;
  /** minutes since the previous line in this thread (ignored on the first line) */
  gap?: number;
  /** pin this line's hour-of-day (0-23), overriding the natural walk */
  hour?: number;
  /** single emoji reaction from the OTHER participant */
  react?: string;
}

export type RecencyBucket =
  | 'today'
  | 'yesterday'
  | 'this_week'
  | 'last_week'
  | 'last_weekend'
  | 'two_weeks'
  | 'this_month'
  | 'last_month'
  | 'two_months'
  | 'dormant';

export interface DmThreadSpec {
  tag: string;
  a: string;
  b: string;
  recency: RecencyBucket;
  lines: DmLine[];
  /** trailing messages sent by the OTHER side that `side` has not read yet */
  unread?: { side: Side; count: number };
  starred?: Side[];
}


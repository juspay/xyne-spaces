/**
 * Type utilities to extract context and output types from WorkflowDefinition
 */
// eslint-disable-next-line @typescript-eslint/no-unused-vars
type ExtractContextFromDefinition<T> = T extends WorkflowDefinition<infer Context, infer _Output, infer _Enum, infer _PreExecute>
  ? Context
  : never

// eslint-disable-next-line @typescript-eslint/no-unused-vars
type ExtractOutputFromDefinition<T> = T extends WorkflowDefinition<infer _Context, infer Output, infer _Enum, infer _PreExecute>
  ? Output
  : never

/**
 * Workflow Type Registry - Auto-generated from WORKFLOW_DEFINITIONS
 * Maps each WorkflowType to its context and output types
 */
export type WorkflowTypeRegistry = {
  [K in WorkflowType]: {
    context: ExtractContextFromDefinition<(typeof import('./definitions'))['WORKFLOW_DEFINITIONS'][K]>
    output: ExtractOutputFromDefinition<(typeof import('./definitions'))['WORKFLOW_DEFINITIONS'][K]>
  }
}

/**
 * Validated workflow task - ensures initialContext matches the workflow type
 * This is a discriminated union of all possible valid workflow tasks
 */
export type ValidatedWorkflowTask = {
  [K in WorkflowType]: {
    workflowType: K
    initialContext: WorkflowTypeRegistry[K]['context']
  }
}[WorkflowType]

/**
 * Discriminated union type for onExecutionComplete callback
 * Allows type narrowing based on workflowType discriminator
 */
export type WorkflowResultUnion<Tasks extends readonly ValidatedWorkflowTask[]> = {
  [K in keyof Tasks]: Tasks[K] extends { workflowType: infer Type extends WorkflowType }
    ? ChildWorkflowResult<WorkflowTypeRegistry[Type]['output']> & { workflowType: Type }
    : never
}[number]

/**
 * Tuple type for onAllCompleted callback
 * Provides exact types for each position in the results array
 */
export type WorkflowResultTuple<Tasks extends readonly ValidatedWorkflowTask[]> = {
  [K in keyof Tasks]: Tasks[K] extends { workflowType: infer Type extends WorkflowType }
    ? ChildWorkflowResult<WorkflowTypeRegistry[Type]['output']>
    : never
}

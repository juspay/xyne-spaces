export interface WorkflowPreview {
  type: 'loadUrlWithUserAgent'
  userAgent: string
  url: string
}

export interface GitInfo {
  branch: string
  commitHash?: string
  baseCommitHash?: string  // Commit hash before agent started making changes (for accurate diff)
  repoUrl?: string
  pullRequestUrl?: string,
  hasCommits?: boolean
  workingDirectory?: string  // Directory where agentic framework performed operations
  pr_link?: string
  // Cached git diff data (computed before repo cleanup)
  gitDiff?: GitDiffFile[]
  diffStats?: GitDiffStats
  // Preview configuration for live preview in dashboard
  preview?: WorkflowPreview
  // Multi-repository support for unified workspace workflows
  multiRepoResults?: {
    [repoName: string]: {
      branch: string
      commitHash: string
      repoUrl: string
      success: boolean
      pullRequestUrl?: string
      pr_link?: string
      error?: string // Error message if the repository operation failed
    }
  }
}

export interface AgenticCheckpointResult {
  result: ConversationResult
  gitInfo: GitInfo
}

export interface WorkflowEngine<
  TContext extends BaseWorkflowContext,
  TEnum extends AnyEnum
> {
  // Get readonly context
  getContext(): Readonly<TContext>

  createCheckpoint<R, Args extends unknown[]>(
    id: TEnum[keyof TEnum],
    handler: CheckpointHandler<R, Args>,
    ...args: Args
  ): Promise<R>
  createAgenticCheckpoint(
    id: TEnum[keyof TEnum],
    agentName: string,
    config: AgenticCheckpointConfig,
    parentStepId?: string
  ): Promise<AgenticCheckpointResult>
  createConditionalStep<Args extends unknown[]>(
    id: TEnum[keyof TEnum],
    condition: ConditionalHandler<Args>,
    ...args: Args
  ): Promise<boolean>
  createExternalStep<R, Args extends unknown[], E = never>(
    id: TEnum[keyof TEnum],
    metadata: ExternalStepMetadata,
    requestHandler: ExternalStepHandler<Args, E>,
    responseProcessor: ExternalResponseProcessor<R, E>,
    ...args: Args
  ): Promise<R>
  createWhileLoop(
    id: TEnum[keyof TEnum],
    maxIterations: number,
    body: WhileLoopBodyFunction<TContext, TEnum>,
    parentStepId?: string
  ): Promise<void>
  createParallelWorkflows<
    const Tasks extends readonly ValidatedWorkflowTask[],
    TFinalResult = void
  >(
    id: TEnum[keyof TEnum],
    config: ParallelWorkflowConfig<Tasks, TFinalResult>,
    parentStepId?: string
  ): Promise<TFinalResult>
  getCurrentState(): WorkflowState<TContext>
  getWorkflowId(): string
  getWorkflowExecutionId(): string
  // Get accumulated agentic checkpoint results for consolidated knowledge generation
  getPendingAgenticResults(): Array<{
    checkpointId: string
    result: ConversationResult
    gitInfo: GitInfo
  }>
}


#!/usr/bin/env node

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sdkRoot = resolve(here, '..');
const repoRoot = resolve(sdkRoot, '../..');
const registryDir = join(sdkRoot, 'src/registry');
const output = join(
  repoRoot,
  'apps/backend/src/api/sdk/catalog-operation-scopes.generated.ts',
);

const resourceFamilies = {
  activities: 'activities',
  automations: 'automations',
  boards: 'boards',
  calls: 'calls',
  canvases: 'canvases',
  channels: 'channels',
  collections: 'collections',
  conversations: 'conversations',
  dashboards: 'dashboards',
  email: 'email',
  forms: 'forms',
  incidents: 'releases',
  messages: 'messages',
  preferences: 'users',
  projects: 'projects',
  recaps: 'recaps',
  'support-tickets': 'tickets',
  tickets: 'tickets',
  'user-groups': 'users',
  users: 'users',
};

const operations = new Map();

for (const filename of readdirSync(registryDir).filter(
  (name) => name.endsWith('.ts') && name !== 'types.ts',
)) {
  const resource = filename.replace(/\.ts$/, '');
  const source = readFileSync(join(registryDir, filename), 'utf8');
  const matches = source.matchAll(/\b(query|mutator)<[\s\S]*?>\(\s*\n?\s*'([^']+)'/g);

  for (const match of matches) {
    const kind = match[1];
    const name = match[2];
    const scope = scopeFor(resource, kind, name);
    const existing = operations.get(name);
    if (existing && existing.kind !== kind) {
      throw new Error(`Catalog operation ${name} is registered as both query and mutator.`);
    }
    const entry = existing ?? { kind, scopes: new Set() };
    entry.scopes.add(scope);
    operations.set(name, entry);
  }
}

function scopeFor(resource, kind, operation) {
  if (resource === 'admin') return 'spaces.admin';

  if (resource === 'workspace') {
    if (operation.startsWith('links.')) return scoped('links', kind);
    if (operation.startsWith('repo.') || operation === 'getAllRepos') {
      return scoped('repos', kind);
    }
    if (operation === 'getAllTicketTags') return scoped('tickets', kind);
    return 'spaces.admin';
  }

  const family = resourceFamilies[resource];
  if (!family) throw new Error(`No OAuth resource-family mapping for registry/${resource}.ts.`);
  return scoped(family, kind);
}

function scoped(family, kind) {
  return `spaces.${family}:${kind === 'query' ? 'read' : 'write'}`;
}

const rows = [...operations.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, entry]) => {
    const scopes = [...entry.scopes].sort().map((scope) => `'${scope}'`).join(', ');
    return `  '${name}': { kind: '${entry.kind}', scopes: [${scopes}] },`;
  })
  .join('\n');

const generated = `/**
 * Generated by packages/xyne-spaces-sdk/scripts/generate-catalog-scopes.mjs.
 * Do not edit by hand; the SDK coverage task checks this file for drift.
 */

export const catalogOperationScopes = {
${rows}
} as const;

export type CatalogOperationName = keyof typeof catalogOperationScopes;
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(output, 'utf8');
  if (current !== generated) {
    console.error('Catalog OAuth scope map is stale. Run: pnpm --filter @xyne/spaces-sdk generate:catalog-scopes');
    process.exit(1);
  }
  console.log(`catalog scopes: ${operations.size} SDK operations mapped`);
} else {
  writeFileSync(output, generated);
  console.log(`wrote ${operations.size} catalog operation scopes to ${output}`);
}

import { describe, it, expect, vi } from 'vitest';
import { render, screen } from '@testing-library/react';
import type { ExecutionRecord } from '@xyne/workflow-sdk';
import { RunsTable } from './RunsTable.js';

/**
 * The table virtualises its rows, and jsdom gives every element a height of zero —
 * so the real virtualizer renders nothing. Stubbed to hand back every row, which
 * is what these assertions are about.
 */
vi.mock('@tanstack/react-virtual', () => ({
  useVirtualizer: ({ count, estimateSize }: { count: number; estimateSize: () => number }) => {
    const size = estimateSize();
    return {
      getVirtualItems: () =>
        Array.from({ length: count }, (_, index) => ({
          index,
          key: index,
          start: index * size,
          end: (index + 1) * size,
          size,
        })),
      getTotalSize: () => count * size,
    };
  },
}));

const run = (over: Partial<ExecutionRecord>): ExecutionRecord => ({
  id: 'exec_00000001',
  workflowId: 'wf_1',
  status: 'COMPLETED',
  createdAt: new Date('2026-03-01T10:00:00.000Z'),
  updatedAt: new Date('2026-03-01T10:00:04.000Z'),
  workflowName: 'Escalate stale backlog',
  ...over,
});

function renderRuns(executions: ExecutionRecord[]) {
  render(<RunsTable executions={executions} onSelectExecution={vi.fn()} />);
}

describe('RunsTable', () => {
  it('shows a waiting run as scheduled, with how long it still has to wait', () => {
    const fireAt = new Date(Date.now() + 102 * 60 * 1000); // 1h 42m
    renderRuns([run({ id: 'exec_sched', status: 'SCHEDULED', fireAt })]);

    expect(screen.getByText('scheduled')).toBeInTheDocument();
    expect(screen.getByText('in 1h 42m')).toBeInTheDocument();
  });

  it('says a scheduled run is due when its moment has passed', () => {
    const fireAt = new Date(Date.now() - 60 * 1000);
    renderRuns([run({ id: 'exec_due', status: 'SCHEDULED', fireAt })]);

    expect(screen.getByText('due now')).toBeInTheDocument();
  });

  it('shows why a run declined to act instead of a duration', () => {
    renderRuns([
      run({
        id: 'exec_skip',
        status: 'SKIPPED',
        endReason: "the workflow's conditions did not match",
      }),
    ]);

    expect(screen.getByText('skipped')).toBeInTheDocument();
    expect(screen.getByText(/conditions did not match/)).toBeInTheDocument();
  });

  it('still shows a duration for a run that actually ran', () => {
    renderRuns([run({ id: 'exec_done' })]);

    expect(screen.getByText('completed')).toBeInTheDocument();
    expect(screen.getByText('4s')).toBeInTheDocument();
  });
});

describe('RunsTable — run name', () => {
  it('heads the column "Run Name"', () => {
    renderRuns([run({ name: 'Loan 4521', nameAutoGenerated: false })]);
    expect(screen.getByRole('columnheader', { name: 'Run Name' })).toBeInTheDocument();
  });

  it('shows a chosen run name', () => {
    renderRuns([run({ name: 'Loan 4521', nameAutoGenerated: false })]);
    expect(screen.getByText('Loan 4521')).toBeInTheDocument();
  });

  it('shows a generated run name too — it is still the unique identifier', () => {
    renderRuns([run({ name: 'Run-2026-03-01-10-00-00-000-UTC', nameAutoGenerated: true })]);
    expect(screen.getByText('Run-2026-03-01-10-00-00-000-UTC')).toBeInTheDocument();
  });

  it('falls back to the short id only when a run has no name at all', () => {
    renderRuns([run({ id: 'abcdef1234567' })]);
    expect(screen.getByText('abcdef12')).toBeInTheDocument();
  });
});
